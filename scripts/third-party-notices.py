#!/usr/bin/env python3
"""L-808c: regenerate the Rust crate section of THIRD-PARTY-NOTICES.md.

    scripts/third-party-notices.py           # rewrite the generated section in place
    scripts/third-party-notices.py --check   # exit 1 when the file is out of date

The crate set is `cargo deny --all-features list -l crate -f json`, i.e. the graph deny.toml checks
(shipped Linux targets, all features, so jemalloc and mimalloc are both listed). The
license expression and repository come from `cargo metadata`. Everything outside the
BEGIN/END markers in THIRD-PARTY-NOTICES.md is hand-written and kept as it is.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "THIRD-PARTY-NOTICES.md")
BEGIN = "<!-- BEGIN generated by scripts/third-party-notices.py -->"
END = "<!-- END generated by scripts/third-party-notices.py -->"


def run(*cmd):
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def section():
    listed = json.loads(run("cargo", "deny", "--all-features", "list", "-l", "crate", "-f", "json"))
    meta = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked", "--all-features"))
    pkgs = {(p["name"], p["version"]): p for p in meta["packages"]}
    rows = []
    for key in listed:
        name, version = key.split(" ")[:2]
        if name == "searchdump-rs":
            continue
        p = pkgs.get((name, version), {})
        lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "?")
        repo = p.get("repository") or ""
        rows.append((name, version, lic, repo))
    rows.sort()
    out = [BEGIN, "", f"{len(rows)} crates.", "", "| crate | version | license (SPDX) | repository |", "|---|---|---|---|"]
    for name, version, lic, repo in rows:
        out.append(f"| {name} | {version} | {lic.replace('|', '/')} | {repo} |")
    out += ["", END]
    return "\n".join(out)


def main():
    text = open(PATH).read()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    new = text[:a] + section() + text[b:]
    if "--check" in sys.argv[1:]:
        if new != text:
            print("third-party notices: OUT OF DATE, run scripts/third-party-notices.py")
            sys.exit(1)
        print("third-party notices: OK")
        return
    open(PATH, "w").write(new)
    print("third-party notices: written")


if __name__ == "__main__":
    main()
