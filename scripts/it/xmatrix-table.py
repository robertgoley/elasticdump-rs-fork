#!/usr/bin/env python3
"""Assemble tests/golden/cross-expectations.toml (TST-API-071) from the actual cells of a
reviewed scripts/it/xmatrix.sh run ($IT_XMATRIX_DIR/actual-*.toml).

    scripts/it/xmatrix-table.py [IT_XMATRIX_DIR] > tests/golden/cross-expectations.toml

Messages are cut to 140 characters (as the test writes them): the test matches expected text as a substring of the
actual message, so the table pins the meaningful start without volatile tails. A table
change is a reviewed commit: compare `git diff` before committing.
"""
import glob
import json
import os
import sys

HEADER = """\
# Cross-version expectation table (TST-API-071), checked by it::xmatrix (TST-API-070).
#
# Key: "<source image> -> <destination image> : <type>"; value: the outcome of restoring the
# source's zstd export of that type on the destination, each type from a clean state:
#   pass                         exit 0, no warning, the object exists (data: same docs)
#   pass-with-warnings[a | b]    exit 0 with these warnings (each listed text is contained in
#                                the actual warning at that position; same count)
#   needs-flag[--flag ...]       fails; passes with the flag(s) its error message names
#   refused[text]                fails; the error message contains text
#   mismatch[text]               exit 0 but the object is missing or the docs differ
# Types without an export (no policy on the ES OSS build) have no cell.
# Generated by scripts/it/xmatrix-table.py from a reviewed run; a change needs a review.

[cells]
"""


def cut(result):
    i = result.find("[")
    if i < 0 or not result.endswith("]"):
        return result
    kind, detail = result[:i], result[i + 1 : -1]
    if kind == "needs-flag":
        return result
    items = detail.split(" | ") if kind == "pass-with-warnings" else [detail]
    return f"{kind}[{' | '.join(x[:140].rstrip() for x in items)}]"


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else os.environ.get(
        "IT_XMATRIX_DIR", os.path.expanduser("~/.cache/searchdump-xmatrix"))
    cells = {}
    for f in sorted(glob.glob(os.path.join(base, "actual-*.toml"))):
        for line in open(f, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            k, v = line.split('" = "', 1)
            cells[json.loads(k + '"')] = cut(json.loads('"' + v))
    sys.stdout.write(HEADER)
    for k in sorted(cells):
        sys.stdout.write(f"{json.dumps(k, ensure_ascii=False)} = {json.dumps(cells[k], ensure_ascii=False)}\n")


if __name__ == "__main__":
    main()
